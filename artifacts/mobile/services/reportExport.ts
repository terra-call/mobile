// Care report export helpers — turn a CareReport into a CSV string or PDF
// file, then hand off to the native share sheet.
//
// expo-print + expo-sharing + expo-file-system all run inside Expo Go, so no
// custom dev build is needed for export to work.

// expo-file-system v55 moved the classic file-write API into the `legacy`
// sub-module while the new top-level API stabilizes. The legacy module still
// works on every platform we target (Expo Go iOS/Android + web fallback).
import * as FileSystem from "expo-file-system/legacy";
import * as Print from "expo-print";
import * as Sharing from "expo-sharing";
import { Timestamp } from "firebase/firestore";
import { Platform } from "react-native";
import type { CareReport, CreateCareReportInput } from "./careReports";

/** Either a saved or just-generated report — the export functions accept both. */
export type ExportableReport = CareReport | CreateCareReportInput;

// ── Formatters ───────────────────────────────────────────────────────────────

function fmtDate(ts: Timestamp | null | undefined): string {
  if (!ts || typeof ts.toDate !== "function") return "—";
  return ts.toDate().toLocaleDateString(undefined, {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
}

function fmtPercent(part: number, total: number): string {
  if (total <= 0) return "—";
  return `${Math.round((part / total) * 100)}%`;
}

// CSV-injection safe: prefix a single quote when the value starts with a
// formula trigger (=, +, -, @, tab, CR) so spreadsheet apps treat it as text
// instead of an executable formula. Then apply standard CSV quoting.
function csvEscape(value: string | number): string {
  let s = String(value);
  if (s.length > 0 && /^[=+\-@\t\r]/.test(s)) {
    s = `'${s}`;
  }
  if (/[",\n]/.test(s)) return `"${s.replace(/"/g, '""')}"`;
  return s;
}

/** Build a CSV string for one report. Two rows: header + values. */
export function formatReportAsCSV(report: ExportableReport): string {
  const rows: string[][] = [
    [
      "Care Recipient",
      "Care Recipient ID",
      "Organization ID",
      "Period Start",
      "Period End",
      "Total Check-Ins",
      "Missed Check-Ins",
      "Emergency Alerts",
      "I'm Not OK Alerts",
      "Compliance %",
      "Avg Response Time (min)",
      "Generated By",
    ],
    [
      report.careReceiverName ?? "",
      report.careReceiverId,
      report.organizationId ?? "",
      fmtDate(report.reportPeriodStart),
      fmtDate(report.reportPeriodEnd),
      String(report.totalCheckIns),
      String(report.missedCheckIns),
      String(report.emergencyAlerts),
      String(report.imNotOkAlerts),
      fmtPercent(
        report.totalCheckIns,
        report.totalCheckIns + report.missedCheckIns,
      ),
      String(report.averageResponseTime),
      report.generatedBy,
    ],
  ];
  return rows.map((r) => r.map(csvEscape).join(",")).join("\n");
}

