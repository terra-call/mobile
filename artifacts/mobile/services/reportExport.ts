function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

// ── Export actions (write file + share sheet) ────────────────────────────────

function safeFilename(report: ExportableReport, ext: "csv" | "pdf"): string {
  const name = (report.careReceiverName ?? "report")
    .replace(/[^a-z0-9]+/gi, "_")
    .replace(/^_+|_+$/g, "")
    .slice(0, 40) || "report";
  const start = report.reportPeriodStart?.toDate?.();
  const stamp = start
    ? `${start.getFullYear()}${String(start.getMonth() + 1).padStart(2, "0")}${String(start.getDate()).padStart(2, "0")}`
    : "report";
  return `${name}_${stamp}.${ext}`;
}

// PHI hygiene helper — remove the temp file once the share sheet closes so
// we do not leave protected health information sitting on the device cache.
async function safeDelete(path: string | undefined): Promise<void> {
  if (!path) return;
  try {
    await FileSystem.deleteAsync(path, { idempotent: true });
  } catch {
    // Best-effort cleanup — the OS will eventually evict cache files.
  }
}

/** Write the CSV to a temp file, open the native share sheet, then delete. */
export async function exportReportAsCSV(report: ExportableReport): Promise<void> {
  const csv = formatReportAsCSV(report);
  const filename = safeFilename(report, "csv");

  // Web fallback — trigger a browser download via Blob.
  if (Platform.OS === "web") {
    const blob = new Blob([csv], { type: "text/csv;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    return;
  }

  // Always write to cacheDirectory (auto-evicted by the OS) — never to
  // documentDirectory, which persists indefinitely and would retain PHI.
  const dir = FileSystem.cacheDirectory;
  if (!dir) throw new Error("No writable cache directory available.");
  const path = `${dir}${filename}`;
  await FileSystem.writeAsStringAsync(path, csv, {
    encoding: FileSystem.EncodingType.UTF8,
  });

  try {
    if (await Sharing.isAvailableAsync()) {
      await Sharing.shareAsync(path, {
        mimeType: "text/csv",
        dialogTitle: "Export Care Report (CSV)",
        UTI: "public.comma-separated-values-text",
      });
    }
  } finally {
    await safeDelete(path);
  }
}

/** Render the report HTML to PDF via expo-print, share, then delete. */
export async function exportReportAsPDF(report: ExportableReport): Promise<void> {
  const html = formatReportAsHTML(report);

  if (Platform.OS === "web") {
    // expo-print on web triggers the print dialog — there's no shareable file.
    await Print.printAsync({ html });
    return;
  }

  const { uri } = await Print.printToFileAsync({ html });
  try {
    if (await Sharing.isAvailableAsync()) {
      await Sharing.shareAsync(uri, {
        mimeType: "application/pdf",
        dialogTitle: "Export Care Report (PDF)",
        UTI: "com.adobe.pdf",
      });
    }
  } finally {
    await safeDelete(uri);
  }
}
